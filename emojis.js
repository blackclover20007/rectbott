export const ALL_EMOJIS = Object.values(EMOJI_CATEGORIES).flat()

export function searchEmoji(query) {
  const q = query.toLowerCase()
  const results = []
  for (const [cat, emojis] of Object.entries(EMOJI_CATEGORIES)) {
    if (cat.toLowerCase().includes(q)) results.push(...emojis)
  }
  return results.length ? results : ALL_EMOJIS.slice(0, 60)
}
